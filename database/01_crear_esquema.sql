-- Ejecutar en pgAdmin conectado a "sgte-db01".
-- Derivado de 27 entidades JPA y la tabla de union usuarios_roles.
-- Los valores @Builder.Default pertenecen a Java; no son DEFAULT de SQL.
BEGIN;

CREATE SCHEMA academico;
CREATE SCHEMA sistema;
CREATE SCHEMA tramites;
CREATE SCHEMA documentos;

-- Catalogos y actores academicos.
CREATE TABLE academico.universidades (
    id_universidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_universidad varchar(255) NOT NULL,
    es_publica boolean NOT NULL
);

CREATE TABLE academico.periodos (
    id_periodo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_periodo varchar(50) NOT NULL UNIQUE,
    nombre_periodo varchar(100),
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL,
    esta_activo boolean,
    es_periodo_actual boolean
);

-- Usuarios, roles y tipos de notificacion.
CREATE TABLE sistema.usuarios (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula varchar(20) NOT NULL UNIQUE,
    nombres varchar(255) NOT NULL,
    apellidos varchar(255) NOT NULL,
    correo_personal varchar(255) UNIQUE,
    correo_institucional varchar(255) NOT NULL UNIQUE,
    telefono varchar(20),
    fecha_nacimiento date,
    genero varchar(20),
    direccion text,
    estado boolean
);

CREATE TABLE sistema.roles (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol varchar(100) NOT NULL UNIQUE,
    descripcion_rol text,
    nivel_jerarquico integer
);

CREATE TABLE sistema.tipos_notificacion (
    id_tipo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_tipo varchar(50) NOT NULL UNIQUE,
    nombre_tipo varchar(100) NOT NULL,
    plantilla_defecto text,
    esta_activo boolean
);

CREATE TABLE academico.facultades (
    id_facultad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_facultad varchar(255) NOT NULL UNIQUE,
    codigo_facultad varchar(20),
    ubicacion_oficina varchar(255),
    telefono_oficina varchar(20),
    email_facultad varchar(255),
    id_universidad integer NOT NULL REFERENCES academico.universidades(id_universidad)
);

CREATE TABLE academico.carreras (
    id_carrera integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_carrera varchar(255) NOT NULL,
    codigo_carrera varchar(50) UNIQUE,
    id_facultad integer NOT NULL REFERENCES academico.facultades(id_facultad),
    duracion_semestres integer,
    modalidad varchar(50)
);

CREATE TABLE academico.estudiantes (
    id_estudiante integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES sistema.usuarios(id_usuario),
    id_carrera integer NOT NULL REFERENCES academico.carreras(id_carrera),
    id_periodo integer REFERENCES academico.periodos(id_periodo),
    numero_semestre integer,
    numero_matricula varchar(50),
    paralelo varchar(1),
    jornada varchar(20),
    estado_academico varchar(50),
    promedio_general numeric(4,2),
    creditos_aprobados integer,
    es_becado boolean,
    fecha_matricula date,
    es_externo boolean,
    id_estudiante_sga integer,
    ultima_sincronizacion timestamp(6) without time zone
);

CREATE TABLE academico.coordinadores (
    id_coordinador integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES sistema.usuarios(id_usuario),
    id_carrera integer REFERENCES academico.carreras(id_carrera),
    ubicacion_oficina varchar(255),
    horario_atencion varchar(255),
    extension_telefonica varchar(20),
    esta_activo boolean,
    fecha_nombramiento date,
    fecha_fin_periodo date,
    id_coordinador_sga integer
);

CREATE TABLE academico.decanos (
    id_decano integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES sistema.usuarios(id_usuario),
    id_facultad integer REFERENCES academico.facultades(id_facultad),
    fecha_nombramiento timestamp(6) without time zone,
    fecha_fin_periodo date,
    resolucion_nombramiento varchar(100),
    esta_activo boolean,
    id_decano_sga integer
);

CREATE TABLE sistema.usuarios_roles (
    id_usuario integer NOT NULL REFERENCES sistema.usuarios(id_usuario),
    id_rol integer NOT NULL REFERENCES sistema.roles(id_rol),
    PRIMARY KEY (id_usuario, id_rol)
);

CREATE TABLE sistema.credenciales (
    id_credencial integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES sistema.usuarios(id_usuario),
    hash_contrasena text NOT NULL,
    nombre_usuario varchar(25),
    estado boolean
);

CREATE TABLE sistema.configuraciones_usuario (
    id_configuracion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES sistema.usuarios(id_usuario),
    ruta_foto_perfil varchar(500),
    ruta_firma_escaneada varchar(500),
    notificar_sms boolean,
    notificar_email boolean,
    notificar_whatsapp boolean,
    notificar_push boolean,
    idioma varchar(10),
    zona_horaria varchar(50)
);

-- Definicion de los tramites y sus flujos.
CREATE TABLE tramites.categorias (
    id_categoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria varchar(255) NOT NULL,
    descripcion_categoria text,
    esta_activo boolean
);

CREATE TABLE tramites.etapas (
    id_etapa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_etapa varchar(255) NOT NULL,
    descripcion text,
    codigo varchar(50) UNIQUE
);

CREATE TABLE tramites.motivos_rechazo (
    id_motivo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_motivo varchar(50) UNIQUE,
    nombre_motivo varchar(255) NOT NULL,
    descripcion_motivo text,
    id_categoria integer REFERENCES tramites.categorias(id_categoria),
    esta_activo boolean
);

CREATE TABLE tramites.flujos_trabajo (
    id_flujo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_flujo varchar(255) NOT NULL,
    descripcion text,
    esta_activo boolean,
    version integer,
    creado_por integer REFERENCES sistema.usuarios(id_usuario)
);

CREATE TABLE tramites.pasos_flujo (
    id_paso integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_flujo integer NOT NULL REFERENCES tramites.flujos_trabajo(id_flujo),
    id_etapa integer NOT NULL REFERENCES tramites.etapas(id_etapa),
    orden_paso integer NOT NULL,
    rol_requerido integer REFERENCES sistema.roles(id_rol),
    id_usuario_encargado integer REFERENCES sistema.usuarios(id_usuario),
    horas_sla integer,
    CONSTRAINT pasos_flujo_id_flujo_orden_paso_key UNIQUE (id_flujo, orden_paso)
);

CREATE TABLE tramites.transiciones_flujo (
    id_transicion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_flujo integer NOT NULL REFERENCES tramites.flujos_trabajo(id_flujo),
    id_paso_origen integer REFERENCES tramites.pasos_flujo(id_paso),
    id_paso_destino integer NOT NULL REFERENCES tramites.pasos_flujo(id_paso),
    observacion boolean,
    documento_generado boolean
);

CREATE TABLE tramites.plantillas_tramite (
    id_plantilla integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_plantilla varchar(255) NOT NULL,
    descripcion_plantilla text,
    id_categoria integer REFERENCES tramites.categorias(id_categoria),
    id_flujo integer REFERENCES tramites.flujos_trabajo(id_flujo),
    id_carrera integer REFERENCES academico.carreras(id_carrera),
    dias_resolucion_estimados integer,
    esta_activo boolean,
    disponible_externos boolean
);

CREATE TABLE tramites.requisitos_plantilla (
    id_requisito integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_plantilla integer NOT NULL REFERENCES tramites.plantillas_tramite(id_plantilla),
    nombre_requisito varchar(255) NOT NULL,
    descripcion_requisito text,
    es_obligatorio boolean,
    tipo_documento varchar(100),
    tamano_max_mb integer,
    extensiones_permitidas varchar(255),
    numero_orden integer
);

CREATE TABLE tramites.ventanas_recepcion (
    id_ventana integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_plantilla integer REFERENCES tramites.plantillas_tramite(id_plantilla),
    id_periodo integer REFERENCES academico.periodos(id_periodo),
    fecha_apertura date NOT NULL,
    fecha_cierre date NOT NULL,
    permite_extension boolean,
    dias_max_extension integer
);

CREATE TABLE tramites.solicitudes (
    id_solicitud integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_solicitud varchar(50) UNIQUE,
    id_plantilla integer NOT NULL REFERENCES tramites.plantillas_tramite(id_plantilla),
    id_usuario integer NOT NULL REFERENCES sistema.usuarios(id_usuario),
    id_carrera integer REFERENCES academico.carreras(id_carrera),
    creado_por integer REFERENCES sistema.usuarios(id_usuario),
    detalles_solicitud text,
    prioridad varchar(20),
    paso_actual integer REFERENCES tramites.pasos_flujo(id_paso),
    estado_actual varchar(50),
    fecha_creacion timestamp(6) without time zone,
    fecha_estimada_fin date,
    fecha_real_fin timestamp(6) without time zone,
    resolucion text
);

CREATE TABLE tramites.historial_solicitud (
    id_historial integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud integer NOT NULL REFERENCES tramites.solicitudes(id_solicitud),
    id_paso integer REFERENCES tramites.pasos_flujo(id_paso),
    id_etapa integer REFERENCES tramites.etapas(id_etapa),
    estado varchar(50) NOT NULL,
    tipo_accion varchar(30),
    procesado_por integer REFERENCES sistema.usuarios(id_usuario),
    comentarios text,
    fecha_entrada timestamp(6) without time zone,
    fecha_completado timestamp(6) without time zone,
    sla_excedido boolean
);

CREATE TABLE tramites.rechazos (
    id_rechazo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud integer NOT NULL REFERENCES tramites.solicitudes(id_solicitud),
    id_motivo integer NOT NULL REFERENCES tramites.motivos_rechazo(id_motivo),
    rechazado_por integer NOT NULL REFERENCES sistema.usuarios(id_usuario),
    comentarios text NOT NULL,
    fecha_rechazo timestamp(6) without time zone,
    notificacion_enviada boolean,
    fecha_notificacion timestamp(6) without time zone
);

-- Archivos y mensajes asociados a solicitudes.
CREATE TABLE documentos.documentos_adjuntos (
    id_documento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud integer NOT NULL REFERENCES tramites.solicitudes(id_solicitud),
    id_requisito integer REFERENCES tramites.requisitos_plantilla(id_requisito),
    nombre_archivo varchar(255) NOT NULL,
    nombre_original varchar(255),
    ruta_archivo varchar(500) NOT NULL,
    tamano_bytes bigint,
    tipo_mime varchar(100),
    checksum varchar(64),
    es_valido boolean,
    mensaje_validacion text,
    subido_por integer REFERENCES sistema.usuarios(id_usuario),
    fecha_subida timestamp(6) without time zone
);

CREATE TABLE documentos.documentos_generados (
    id_generado integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud integer NOT NULL REFERENCES tramites.solicitudes(id_solicitud),
    tipo_documento varchar(100) NOT NULL,
    codigo_documento varchar(100) UNIQUE,
    ruta_archivo varchar(500) NOT NULL,
    plantilla_usada varchar(255),
    generado_por integer REFERENCES sistema.usuarios(id_usuario),
    firmado_por integer REFERENCES sistema.usuarios(id_usuario),
    firma_digital text,
    es_oficial boolean,
    fecha_generacion timestamp(6) without time zone,
    valido_hasta date
);

CREATE TABLE sistema.notificaciones (
    id_notificacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo integer NOT NULL REFERENCES sistema.tipos_notificacion(id_tipo),
    id_usuario integer NOT NULL REFERENCES sistema.usuarios(id_usuario),
    id_solicitud integer REFERENCES tramites.solicitudes(id_solicitud),
    titulo varchar(255) NOT NULL,
    mensaje text NOT NULL,
    canal varchar(50),
    esta_leida boolean,
    fecha_lectura timestamp(6) without time zone,
    esta_enviada boolean,
    fecha_envio timestamp(6) without time zone,
    error_envio text,
    programada_para timestamp(6) without time zone,
    fecha_creacion timestamp(6) without time zone
);

COMMIT;
